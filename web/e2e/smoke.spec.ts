import { expect, test } from '@playwright/test';
test('real backend insertion is verified before CPDLC, and snapshot inspection pauses live sky',async({page,request})=>{
  test.setTimeout(150000);
  await request.post('/api/control',{data:{action:'pause'}});
  await expect.poll(async()=>{const world=await(await request.get('/api/state')).json();return world.queue_size>0||world.flights.some((f:{status:string})=>f.status==='solving');},{timeout:90000,intervals:[1000]}).toBe(false);
  const response=await request.post('/api/control',{data:{action:'reset',scenario:'hero_crossing'}});expect(response.ok()).toBeTruthy();
  await page.goto('/#explore');
  await expect(page.getByRole('button',{name:'Enter full screen'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Play simulation'})).toBeEnabled();
  await expect(page.getByText('AWAITING VERIFICATION',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'File crossing flight',exact:true}).click();
  await expect(page.getByText('VERIFIED CLEARANCE',{exact:true})).toBeVisible({timeout:45000});
  await page.screenshot({path:'test-results/orbit-control-room.png',fullPage:true});
  await page.getByRole('button',{name:'Inside ORBIT 2',exact:true}).click();
  await expect(page.getByText('Not connected',{exact:true})).toBeVisible();
  await expect(page.getByText('Reduced basis · not the full edge / slack encoding',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/orbit-inside.png',fullPage:true});
  await page.getByRole('button',{name:'Flight deck 3',exact:true}).click();
  await expect(page.getByText('VERIFIED MESSAGE RECEIVED',{exact:true})).toBeVisible();
  await expect(page.getByRole('region',{name:'Cockpit view for XAT417'})).toBeVisible();
  await expect(page.getByRole('button',{name:'View XAT417 cockpit',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Pause cockpit preview',exact:true}).click();
  const preview=page.getByRole('slider',{name:'Cockpit route preview position'});
  await preview.fill('30000');
  await expect(page.locator('.cockpit-live-data .cockpit-phase')).toHaveText('Filed route rejoined');
  await page.getByRole('button',{name:'Replay cockpit manoeuvre'}).click();
  await expect(page.getByRole('button',{name:'Pause cockpit preview',exact:true})).toBeVisible();
  const ocean=page.locator('.cockpit-sea-flow');
  const firstFrame=await ocean.getAttribute('d');
  await expect.poll(()=>ocean.getAttribute('d')).not.toBe(firstFrame);
  await page.getByRole('button',{name:'Pause cockpit preview',exact:true}).click();
  const pausedFrame=await ocean.getAttribute('d');
  await page.waitForTimeout(300);
  expect(await ocean.getAttribute('d')).toBe(pausedFrame);
  await preview.fill('11000');
  expect((await(await request.get('/api/state')).json()).sim_time_s).toBe(0);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/orbit-cockpit.png',fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:/INSERTION HISTORY/}).click();
  await page.getByRole('button',{name:'Inspect XAT417 insertion'}).click();
  await expect(page.getByText('Snapshot inspection · live controls paused',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Play simulation'})).toBeDisabled();
  await page.getByRole('button',{name:'Return to live',exact:true}).first().click();
  await expect(page.getByRole('button',{name:'Play simulation'})).toBeEnabled();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button',{name:'Enter full screen'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/orbit-mobile.png',fullPage:true});
});
